window.getLang = function () {
  const stored = localStorage.getItem(window.KS_LANG_KEY);
  return stored && window.I18N[stored] ? stored : "en";
};

window.setLang = function (lang) {
  if (!window.I18N[lang]) lang = "en";
  localStorage.setItem(window.KS_LANG_KEY, lang);
  document.documentElement.lang = lang;
  return lang;
};

window.t = function (key, vars) {
  const lang = window.getLang();
  let str = (window.I18N[lang] && window.I18N[lang][key]) || window.I18N.en[key] || key;
  if (vars) {
    str = str.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
  }
  return str;
};

window.translatePage = function () {
  document.querySelectorAll("[data-i18n]").forEach(function (node) {
    node.textContent = window.t(node.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(function (node) {
    node.placeholder = window.t(node.getAttribute("data-i18n-placeholder"));
  });
  document.querySelectorAll("[data-lang-btn]").forEach(function (btn) {
    btn.classList.toggle("active", btn.getAttribute("data-lang-btn") === window.getLang());
  });
};